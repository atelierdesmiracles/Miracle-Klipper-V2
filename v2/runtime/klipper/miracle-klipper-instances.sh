#!/bin/sh
# Multi-printer data scaffolding inspired by KIAUH instance management.
# Creates isolated config/gcode/log/comms directories and Moonraker configs.
# Does not start extra instances until the Android supervisor has per-instance support.
set -eu

DATA="/var/lib/miracle-klipper"
BASE="/opt/miracle-klipper"
PORT_BASE=7125
NAME_RE='^[a-zA-Z0-9][a-zA-Z0-9_-]{0,23}$'

usage() {
  echo "Usage:"
  echo "  $0 list"
  echo "  $0 create NAME"
  echo "  $0 remove NAME   (requires typing REMOVE NAME)"
}

list_instances() {
  found=0
  for dir in "$DATA"/instances/*; do
    [ -d "$dir" ] || continue
    found=1
    name="${dir##*/}"
    printf '%-24s Moonraker port: ' "$name"
    if [ -f "$dir/instance.env" ]; then
      # File is generated by this script and contains only PORT=digits.
      . "$dir/instance.env"
      printf '%s\n' "${PORT:-unknown}"
    else
      echo "unknown (metadata missing)"
    fi
  done
  [ "$found" -eq 1 ] || echo "No additional printer instances."
}

next_port() {
  used=" "
  for file in "$DATA"/instances/*/instance.env; do
    [ -f "$file" ] || continue
    . "$file"
    used="$used${PORT:-} "
  done
  port="$PORT_BASE"
  while :; do
    case "$used" in *" $port "*) port=$((port + 1));; *) printf '%s\n' "$port"; return;; esac
  done
}

create_instance() {
  name="$1"
  printf '%s\n' "$name" | grep -Eq "$NAME_RE" || {
    echo "Invalid name: use 1-24 letters, digits, '_' or '-'; first char alphanumeric." >&2
    exit 2
  }
  target="$DATA/instances/$name"
  [ ! -e "$target" ] || { echo "Instance already exists: $name" >&2; exit 1; }
  port="$(next_port)"
  mkdir -p "$target"/{config,gcodes,logs,comms}
  cat > "$target/instance.env" <<EOF
NAME=$name
PORT=$port
EOF
  cat > "$target/config/printer.cfg" <<EOF
# Miracle Klipper instance: $name
# Configure the actual MCU, kinematics, motion limits, heaters and safety
# parameters for this printer before enabling its Klipper process.
EOF
  cat > "$target/config/moonraker.conf" <<EOF
[server]
host: 127.0.0.1
port: $port
klippy_uds_address: $target/comms/klippy.sock
max_upload_size: 1024

[authorization]
trusted_clients:
  127.0.0.0/8
  ::1/128
cors_domains:
  localhost
  127.0.0.1

[file_manager]
enable_object_processing: True
config_path: $target/config

[history]
EOF
  chmod 600 "$target/instance.env"
  echo "Created isolated data/config for '$name' on Moonraker port $port."
  echo "Runtime registration is not active yet: Android supervisor must add per-instance process control."
}

remove_instance() {
  name="$1"
  printf '%s\n' "$name" | grep -Eq "$NAME_RE" || { echo "Invalid name" >&2; exit 2; }
  target="$DATA/instances/$name"
  [ -d "$target" ] || { echo "Instance not found" >&2; exit 1; }
  echo "This permanently deletes $target and all its G-code and configuration."
  printf 'Type REMOVE %s to continue: ' "$name"
  IFS= read -r answer
  [ "$answer" = "REMOVE $name" ] || { echo "Cancelled"; exit 1; }
  timestamp="$(date -u '+%Y%m%d-%H%M%S')"
  mkdir -p "$DATA/backups"
  tar -czf "$DATA/backups/instance-$name-before-remove-$timestamp.tar.gz" -C "$DATA/instances" "$name"
  rm -rf "$target"
  echo "Removed '$name'. Pre-removal archive saved in $DATA/backups."
}

case "${1:-}" in
  list) list_instances ;;
  create) [ "$#" -eq 2 ] || { usage; exit 2; }; create_instance "$2" ;;
  remove) [ "$#" -eq 2 ] || { usage; exit 2; }; remove_instance "$2" ;;
  *) usage; exit 2 ;;
esac
